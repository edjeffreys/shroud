#!/usr/bin/env bash
# Rerun only to pick up API a newer 1.x adds; the 1.x ABI never breaks existing bindings.
# Usage: scripts/gen-bindings.sh <libvt-prefix>   (contains include/ghostty/vt.h)
set -euo pipefail
prefix="${1:?usage: $0 <libvt-prefix>}"
out="$(dirname "$0")/../crates/vt/src/ffi.rs"

{
  echo "// Generated by scripts/gen-bindings.sh from libghostty-vt headers. Do not edit."
  bindgen "$prefix/include/ghostty/vt.h" \
    --allowlist-function 'ghostty_.*' \
    --allowlist-type 'Ghostty.*' \
    --allowlist-var 'GHOSTTY_.*' \
    --no-prepend-enum-name \
    --use-core \
    -- -I"$prefix/include" -DGHOSTTY_STATIC
} > "$out"
echo "wrote $out"
